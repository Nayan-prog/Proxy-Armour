"""Manage the Proxy Armour Docker stack. Standard library only - any Python 3.10+.

    python scripts/stack.py up        build + start everything, wait until healthy
    python scripts/stack.py down      stop (add --volumes to also delete the database)
    python scripts/stack.py logs      follow logs (optionally: logs proxy scanner)
    python scripts/stack.py test      run the test suite inside the scanner container
                                      (incl. the PostgreSQL tests against armour_test)
    python scripts/stack.py seed      create/replace the admin login + default policies
                                      (--password X, or $ARMOUR_ADMIN_PASSWORD, else random;
                                       --reset-policies restores config.yaml defaults)
    python scripts/stack.py demo      send sample secrets in every provider format through
                                      the proxy to the mock LLM and check restoration
    python scripts/stack.py ps        container status

The Makefile and scripts/armour.ps1 are thin wrappers around this file.
"""
import argparse
import os
import secrets
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / ".env.docker"
CERT = ROOT / "certs" / "mitmproxy-ca-cert.pem"


def compose(*args: str, input_text: str | None = None, capture: bool = False) -> subprocess.CompletedProcess:
    cmd = ["docker", "compose", *args]
    result = subprocess.run(cmd, cwd=ROOT, text=True, input=input_text,
                            stdout=subprocess.PIPE if capture else None)
    if result.returncode != 0:
        sys.exit(f"command failed ({result.returncode}): {' '.join(cmd)}")
    return result


def read_env() -> dict[str, str]:
    values = {}
    for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip().strip("'")
    return values


def set_env(key: str, value: str) -> None:
    """Replace KEY=... in .env.docker. Single quotes: compose must not expand the $ in bcrypt hashes."""
    lines = ENV_FILE.read_text(encoding="utf-8").splitlines()
    new = f"{key}='{value}'"
    lines = [new if line.startswith(f"{key}=") else line for line in lines]
    if new not in lines:
        lines.append(new)
    ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def ensure_env() -> None:
    """Create .env.docker with fresh random secrets on first use (never overwritten)."""
    (ROOT / "certs").mkdir(exist_ok=True)
    if ENV_FILE.exists():
        return
    db_password = secrets.token_hex(16)            # hex: safe inside a URL
    ENV_FILE.write_text(f"""# Generated by scripts/stack.py - secrets for the Docker stack. Git-ignored; keep it private.
POSTGRES_USER=armour
POSTGRES_PASSWORD={db_password}
POSTGRES_DB=proxy_armour
DATABASE_URL=postgresql+psycopg://armour:{db_password}@postgres:5432/proxy_armour
# throwaway database used by `stack.py test` (created by docker/postgres-init)
TEST_DATABASE_URL=postgresql+psycopg://armour:{db_password}@postgres:5432/armour_test
REDIS_URL=redis://redis:6379/0
JWT_SECRET={secrets.token_urlsafe(48)}
EVENTS_SHARED_SECRET={secrets.token_urlsafe(32)}
ADMIN_USERNAME=admin
# set by `stack.py seed` (bcrypt hash only - the password is never stored)
ADMIN_PASSWORD_HASH=
""", encoding="utf-8")
    try:
        os.chmod(ENV_FILE, 0o600)
    except OSError:
        pass
    print(f"created {ENV_FILE.name} with random secrets")


def cmd_up(args) -> None:
    ensure_env()
    compose("up", "-d", "--build", "--wait")
    print("\nProxy Armour is running:")
    print("  dashboard   http://localhost:3000")
    print("  admin API   http://localhost:8000/docs")
    print(f"  proxy       http://localhost:8080   (trust {Path('certs') / CERT.name})")
    if not read_env().get("ADMIN_PASSWORD_HASH"):
        print("\nNo admin login yet - run:  python scripts/stack.py seed")


def cmd_down(args) -> None:
    compose("down", *(["--volumes"] if args.volumes else []))


def cmd_logs(args) -> None:
    compose("logs", "-f", "--tail", "100", *args.services)


def cmd_ps(args) -> None:
    compose("ps")


def cmd_test(args) -> None:
    # tests describe the shipped config.yaml, so the container overlay is switched
    # off (test_config covers the overlay itself); TEST_DATABASE_URL from
    # .env.docker makes the database tests also run against PostgreSQL
    compose("exec", "-T", "-e", "ARMOUR_CONFIG_OVERLAY=", "scanner",
            "python", "-m", "pytest", "-q", "-p", "no:cacheprovider", *args.pytest_args)


def cmd_seed(args) -> None:
    ensure_env()
    compose("up", "-d", "--wait", "scanner")
    password = args.password or os.environ.get("ARMOUR_ADMIN_PASSWORD")
    generated = password is None
    if generated:
        password = secrets.token_urlsafe(15)
    # hashed inside the container (bcrypt is installed there); password via stdin, not argv
    hashed = compose("exec", "-T", "scanner", "python", "-m", "app.seed", "hash",
                     input_text=password + "\n", capture=True).stdout.strip()
    set_env("ADMIN_PASSWORD_HASH", hashed)
    compose("up", "-d", "--wait", "scanner")      # recreated with the new hash
    compose("exec", "-T", "scanner", "python", "-m", "app.seed", "policies",
            *(["--reset"] if args.reset_policies else []))
    username = read_env().get("ADMIN_USERNAME", "admin")
    print(f"\nAdmin login for http://localhost:3000 :  {username} / "
          f"{password if generated else '(the password you chose)'}")
    if generated:
        print("Save this password now - only its bcrypt hash is stored (.env.docker).")


def cmd_demo(args) -> None:
    compose("exec", "-T", "proxy", "python", "scripts/demo.py",
            "--proxy", "http://127.0.0.1:8080", "--ca", "/certs/mitmproxy-ca-cert.pem")


def main() -> None:
    parser = argparse.ArgumentParser(description="Proxy Armour Docker stack")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("up").set_defaults(fn=cmd_up)
    down = sub.add_parser("down")
    down.add_argument("--volumes", action="store_true", help="also delete the database volume")
    down.set_defaults(fn=cmd_down)
    logs = sub.add_parser("logs")
    logs.add_argument("services", nargs="*")
    logs.set_defaults(fn=cmd_logs)
    sub.add_parser("ps").set_defaults(fn=cmd_ps)
    test = sub.add_parser("test", help="extra arguments (e.g. -k name -x) go to pytest")
    test.add_argument("pytest_args", nargs="*")
    test.set_defaults(fn=cmd_test)
    seed = sub.add_parser("seed")
    seed.add_argument("--password", help="admin password (default: $ARMOUR_ADMIN_PASSWORD or random)")
    seed.add_argument("--reset-policies", action="store_true", help="restore config.yaml default policies")
    seed.set_defaults(fn=cmd_seed)
    sub.add_parser("demo").set_defaults(fn=cmd_demo)
    argv = sys.argv[1:]
    if argv[:1] == ["test"]:
        # everything after `test` goes to pytest verbatim and in order (-k, -x, paths...)
        cmd_test(argparse.Namespace(pytest_args=argv[1:]))
        return
    args = parser.parse_args(argv)
    args.fn(args)


if __name__ == "__main__":
    main()
